`timescale 1ns / 1ps

module fmc150_axi_capture (
    // 1. FMC150 Physical Hardware Pins
    input wire fmc_clk_p,
    input wire fmc_clk_n,
    input wire [6:0] fmc_data_p,
    input wire [6:0] fmc_data_n,

    // 2. AXI4-Stream Master Interface (To connect to the DMA)
    input wire aclk,          // System clock for the AXI interface
    input wire aresetn,       // Active-low reset from the processing system
    output reg [15:0] m_axis_tdata, // 16-bit wide data bus (padded 14-bit)
    output reg m_axis_tvalid        // Tells the DMA "This data is valid, read it!"
);

    // Internal wire to catch the reconstructed 14-bit word from the ISERDES
    wire [13:0] raw_14bit_data;
    
    // Internal wire for the divided clock generated by the ISERDES
    wire div_clk; 

    // Instantiate the SelectIO Wizard IP you already configured
    selectio_wiz_0 iserdes_front_door (
        .data_in_from_pins_p(fmc_data_p),
        .data_in_from_pins_n(fmc_data_n),
        .clk_in_p(fmc_clk_p),
        .clk_in_n(fmc_clk_n),
        .clk_reset(~aresetn),
        .io_reset(~aresetn),
        .data_in_to_device(raw_14bit_data),
        .clk_out(div_clk) 
    );

    // Synchronize the raw data into the AXI-Stream format
    always @(posedge div_clk) begin
        if (~aresetn) begin
            m_axis_tvalid <= 1'b0;
            m_axis_tdata <= 16'd0;
        end else begin
            // We are constantly receiving data, so valid is always HIGH
            m_axis_tvalid <= 1'b1; 
            
            // Pad the 14-bit ADC data with two leading zeroes to make it 16-bit AXI compliant
            m_axis_tdata <= {2'b00, raw_14bit_data}; 
        end
    end

endmodule