`timescale 1ns / 1ps

module top_stage1 (
    input  wire       clk_sys,       // System clock for reading (e.g. 100 MHz for AXI-DMA later)
    input  wire       fmc_clk_p,
    input  wire       fmc_clk_n,  
    input  wire [6:0] fmc_data_p,    // 7 LVDS positive lanes from FMC
    input  wire [6:0] fmc_data_n,    // 7 LVDS negative lanes from FMC
    input  wire       reset,         // Active-high reset
    input  wire       trigger,       // Start capture signal
    output reg        tx_ready       // Wakes up processor/DMA when capture is done
);

    // Internal wires for the ISERDES block
    wire        clk_125mhz;          // Slow clock generated by ISERDES
    wire [27:0] raw_28bit_data;      // The double-sample output (two 14-bit samples)

    reg         we;
    reg  [8:0]  write_addr;          // 9 bits to count 0 to 511 (512 writes * 2 = 1024 samples)
    wire [27:0] read_data;           // Read data width updated to match 28-bit write

    // FSM States
    localparam IDLE    = 2'b00;
    localparam CAPTURE = 2'b01;
    localparam DONE    = 2'b10;
    reg [1:0] state;

    // --- NEW: Xilinx ISERDES Reset Sequencer ---
    // Holds the io_reset high for 4 extra system clock cycles after main reset drops
    reg [3:0] reset_shift;
    wire io_reset_staggered = reset_shift[3];

    always @(posedge clk_sys or posedge reset) begin
        if (reset) begin
            reset_shift <= 4'b1111;
        end else begin
            reset_shift <= {reset_shift[2:0], 1'b0}; // Shift in zeros to naturally drop the line
        end
    end
    // -------------------------------------------

    // 1. Instantiate the SelectIO Wizard IP
    selectio_wiz_0 iserdes_inst (
        .data_in_from_pins_p(fmc_data_p),
        .data_in_from_pins_n(fmc_data_n),
        .clk_in_p(fmc_clk_p),
        .clk_in_n(fmc_clk_n),
        .clk_div_out(clk_125mhz),
        .data_in_to_device(raw_28bit_data),
        .bitslip(7'b0000000),
        .clk_reset(reset),                   // Drops immediately
        .io_reset(io_reset_staggered)        // Drops 4 clock cycles later
    );
    // Explicitly unpack the data so we can see the clean 14-bit analog waves in simulation
    wire [13:0] sample_1 = raw_28bit_data[13:0];
    wire [13:0] sample_2 = raw_28bit_data[27:14];

    // 2. Instantiate BRAM Buffer 
    bram_buffer u_bram (
        .clk_write(clk_125mhz),
        .we(we),
        .write_addr(write_addr),
        .data_in(raw_28bit_data),    
        .clk_read(clk_sys),
        .read_addr(9'd0),            
        .data_out(read_data)
    );

    // 3. Finite State Machine 
    always @(posedge clk_125mhz or posedge reset) begin
        if (reset) begin
            state <= IDLE;
            write_addr <= 9'd0;
            we <= 1'b0;
            tx_ready <= 1'b0;
        end else begin
            case (state)
                IDLE: begin
                    write_addr <= 9'd0;
                    we <= 1'b0;
                    tx_ready <= 1'b0;
                    if (trigger) state <= CAPTURE;
                end
                
                CAPTURE: begin
                    we <= 1'b1;
                    if (write_addr == 9'd511) begin
                        state <= DONE; 
                        we <= 1'b0;
                    end else begin
                        write_addr <= write_addr + 1;
                    end
                end
                
                DONE: begin
                    we <= 1'b0;
                    tx_ready <= 1'b1; 
                end
                
                default: state <= IDLE;
            endcase
        end
    end

endmodule